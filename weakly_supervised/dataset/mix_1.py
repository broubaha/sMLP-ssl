import torch
import numpy as np
from copy import deepcopy

# ─────────────────────────────────────────────
# MixUp variants
# ─────────────────────────────────────────────

def mixup_soft(data, target=None, max=None, alpha=1.0):
    """
    Soft MixUp augmentation for labelled data with one-hot targets.

    Linearly interpolates both images and their labels between two randomly
    paired samples. The mixing coefficient lam is clipped to [0.4, 0.6] to
    avoid degenerate mixtures (one sample dominating the other).

    Args:
        data   : image batch tensor of shape (B, C, H, W)
        target : one-hot label tensor of shape (B, num_classes)
        max    : optional confidence scores — if provided, also returns the
                 paired confidence scores (used for threshold propagation)
        alpha  : Beta distribution parameter (alpha=1 → uniform on [0,1])

    Returns:
        (mixedup_data, mixedup_target) or
        (mixedup_data, mixedup_target, max, max[indices]) if max is not None
    """
    # Random pairing within the batch
    indices      = torch.randperm(len(data)).to(data.device)
    shuffled_data = data[indices]

    # Symmetric Beta draw clipped to [0.4, 0.6] — avoids near-identity mixtures
    lam = np.clip(np.random.beta(alpha, alpha), 0.4, 0.6)

    mixedup_data   = lam * data   + (1 - lam) * shuffled_data
    mixedup_target = lam * target + (1 - lam) * target[indices]

    if max is not None:
        return mixedup_data, mixedup_target, max, max[indices]
    return mixedup_data, mixedup_target


def mixup_hard(data, indices, alpha=1.0):
    """
    Hard MixUp augmentation for unlabelled data (no label mixing).

    Unlike mixup_soft, labels are not mixed here — the pairing indices and
    lam are returned separately so the caller can apply the appropriate
    label interpolation on pseudo-labels outside this function.

    Args:
        data    : image batch tensor of shape (B, C, H, W)
        indices : pre-computed permutation indices for pairing (avoids
                  re-drawing inside the function for consistency with CutMix)
        alpha   : Beta distribution parameter

    Returns:
        (mixedup_data, lam)
    """
    shuffled_data = data[indices]
    lam = np.clip(np.random.beta(alpha, alpha), 0.4, 0.6)
    mixedup_data  = lam * data + (1 - lam) * shuffled_data
    return mixedup_data, lam


# ─────────────────────────────────────────────
# CutMix variants
# ─────────────────────────────────────────────

def cutmix_soft(data, target, max=None, alpha=1.0):
    """
    Soft CutMix augmentation for labelled data with one-hot targets.

    Cuts a rectangular region from one image and pastes it onto another,
    mixing labels proportionally to the area of the pasted patch.
    lam is symmetrised (max(lam, 1-lam)) to ensure the dominant image
    always contributes at least 50% of the pixels.

    Args:
        data   : image batch tensor (B, C, H, W) — modified in place
        target : one-hot label tensor (B, num_classes)
        max    : optional confidence scores
        alpha  : Beta distribution parameter

    Returns:
        (data, mixed_target) or (data, mixed_target, max, max[indices])
    """
    indices       = torch.randperm(data.size(0))
    shuffled_data = data[indices]

    lam = np.random.beta(alpha, alpha)
    lam = max(lam, 1 - lam)  # symmetrise: dominant image contributes ≥ 50%

    bbx1, bby1, bbx2, bby2 = rand_bbox(data.size(), lam)

    # Paste the patch from the paired image into the current image
    data[:, :, bbx1:bbx2, bby1:bby2] = shuffled_data[:, :, bbx1:bbx2, bby1:bby2]

    # Recompute lam from actual pixel ratio (accounts for boundary clipping)
    lam    = 1 - ((bbx2 - bbx1) * (bby2 - bby1) / (data.size()[-1] * data.size()[-2]))
    target = lam * target + (1 - lam) * target[indices]

    if max is not None:
        return data, target, max, max[indices]
    return data, target


def cutmix_hard(data, indices, bbox, alpha=1.0):
    """
    Hard CutMix augmentation for unlabelled data.

    Instead of computing a bounding box from scratch, uses a pre-computed
    binary mask (bbox) generated by rand_bbox() at dataset loading time.
    This ensures that the same spatial mask is shared between the weak view
    (used for pseudo-label generation) and the mixed view (used for loss
    computation), maintaining consistency between them.

    The mixing is done via element-wise masking:
        mixed = data * (1 - mask) + shuffled_data * mask

    Label mixing is handled in the training loop using the returned lam value.

    Args:
        data    : image batch tensor (B, C, H, W)
        indices : pre-computed pairing permutation (shared with mixup_hard)
        bbox    : binary spatial mask tensor (H, W), pre-computed by rand_bbox()
        alpha   : unused here (bbox already encodes the mixing geometry)

    Returns:
        data_cut : CutMix-augmented batch (B, C, H, W)
    """
    data_cut      = deepcopy(data)
    shuffled_data = data[indices]

    # Apply binary mask: 0 = keep original, 1 = paste from paired image
    # bbox.unsqueeze(1) broadcasts the (H, W) mask to (B, C, H, W)
    data_cut = data * (1 - bbox.unsqueeze(1)) + shuffled_data * bbox.unsqueeze(1)

    return data_cut


# ─────────────────────────────────────────────
# Bounding box / mask generator
# ─────────────────────────────────────────────

def rand_bbox(size, alpha=1.0):
    """
    Generates a random CutMix patch as a binary spatial mask.

    The patch size is determined by a Beta-distributed lam:
        cut_ratio = sqrt(1 - lam)   →   patch covers (1-lam) fraction of the image

    lam is symmetrised (max(lam, 1-lam)) so the patch covers at most 50%
    of the image area, ensuring the original image always dominates.

    The patch centre (cx, cy) is drawn uniformly over the spatial grid,
    and the patch corners are clipped to image boundaries.

    The actual lam is recomputed from the clipped patch area to reflect
    the true mixing ratio after boundary clipping.

    Args:
        size  : image size tuple, at least (..., W, H)
        alpha : Beta distribution parameter (default 1.0 → uniform)

    Returns:
        mask : binary torch.Tensor of shape (W, H),
               1 inside the patch, 0 outside
        lam  : actual mixing coefficient after boundary adjustment
    """
    lam = np.random.beta(alpha, alpha)
    lam = np.max([lam, 1 - lam])  # symmetrise: patch ≤ 50% of image area

    W = size[-2]
    H = size[-1]

    # Patch dimensions proportional to sqrt(1 - lam)
    cut_rat = np.sqrt(1. - lam)
    cut_w   = int(W * cut_rat)
    cut_h   = int(H * cut_rat)

    # Random patch centre, uniformly distributed over the spatial grid
    cx = np.random.randint(W)
    cy = np.random.randint(H)

    # Patch corners, clipped to image boundaries
    bbx1 = np.clip(cx - cut_w // 2, 0, W)
    bby1 = np.clip(cy - cut_h // 2, 0, H)
    bbx2 = np.clip(cx + cut_w // 2, 0, W)
    bby2 = np.clip(cy + cut_h // 2, 0, H)

    # Recompute lam from actual clipped area
    lam = 1 - ((bbx1 - bbx2) * (bby1 - bby2) / (W * H))

    # Build binary mask: 1 inside patch, 0 outside
    mask = torch.zeros(W, H)
    mask[bbx1:bbx2, bby1:bby2] = 1

    return mask, lam


